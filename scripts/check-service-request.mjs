import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.RESPONSIVE_BASE_URL || 'http://localhost:5173/';
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
const pdf = { name: 'ready-proposal.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\nTest proposal') };
const docx = { name: 'reference.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('Test document') };
const route = 'contact.html';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const posts = [];
  let outcome = 'error';
  // This test must never deliver a real enquiry, even if an endpoint is configured.
  await page.route('**/*', async intercepted => {
    if (intercepted.request().method() !== 'POST') return intercepted.continue();
    posts.push(intercepted.request().postDataBuffer()?.toString() || '');
    await new Promise(resolve => setTimeout(resolve, 150));
    return intercepted.fulfill({ status: outcome === 'error' ? 503 : 200, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': new URL(base).origin }, body: JSON.stringify({ ok: outcome === 'success' }) });
  });
  await page.goto(new URL(route, base).href);
  await page.locator('[data-request-ready="true"]').waitFor();
  await page.evaluate(() => document.fonts.ready);
  const published = await readFile(new URL('../services.html', import.meta.url), 'utf8');
  const names = [...published.matchAll(/<article><div><h2>([^<]+)<\/h2>/g)].map(match => match[1]);
  const options = await page.locator('.request-service-options label>span').allTextContents();
  assert.equal(names.length, 10);
  names.forEach(name => assert(options.includes(name), `Missing service: ${name}`));
  assert.equal(options.length, 12);
  assert.equal(await page.locator('#request-service-picker').getAttribute('open'), null);
  assert.equal(await page.locator('#request-extra-details').getAttribute('open'), null);
  assert.equal(await page.locator('#request-stage,#request-project,#request-website,#request-audience,#request-timeline,#request-budget').count(), 0);
  assert.equal(await page.locator('#request-editor [required]').count(), 3, 'Only name, email and consent are unconditionally required');
  await page.locator('#request-name').fill('Test client');
  await page.locator('#request-email').fill('client@example.test');
  await page.locator('[name=consent]').check();
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-services-error').isVisible());
  assert(await page.locator('#request-service-picker').evaluate(e => e.open), 'Invalid service picker must open');
  await page.locator('[name=services][value=not-sure]').check();
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-editor').isVisible(), 'A note or proposal is required');
  assert.match(await page.locator('#request-message').evaluate(e => e.validationMessage), /note or attach/);
  await page.locator('#request-message').fill('New logo');
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-review').isVisible(), 'A brief note is enough without optional fields');
  assert(!/Not provided|To discuss/.test(await page.locator('#request-summary').textContent()), 'Do not fill review with unanswered questions');
  await page.locator('#request-edit').click();
  await page.locator('#request-message').fill('');
  await page.locator('#request-proposals').setInputFiles(pdf);
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-review').isVisible(), 'Proposal-only requests must not require a typed brief');
  await page.locator('#request-edit').click();
  await page.locator('#request-file-list button').click();
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-editor').isVisible(), 'Removing the only proposal must restore note validation');
  await page.locator('#request-proposals').setInputFiles({ name: 'invalid.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('not a proposal') });
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-editor').isVisible(), 'Rejected files must not count as a brief');
  await page.locator('[name=services][value=not-sure]').uncheck();
  await page.locator('#request-extra-details>summary').click();
  await page.locator('#request-company').fill('<img src=x onerror=alert(1)>');
  await page.locator('#request-message').fill('We would like to develop a clear new brand identity for our organisation.');
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-services-error').isVisible());
  await page.locator('#request-other').check();
  assert(await page.locator('#request-other-description').isVisible());
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-editor').isVisible());
  await page.locator('#request-other-description').fill('A bespoke service to discuss');
  await page.locator('[name=services][value=visual-identity]').check();
  assert.match(await page.locator('#request-services-selection').textContent(), /Visual identity/);
  await page.locator('#request-service-picker>summary').click();
  await page.locator('#request-other-description').evaluate(e => { e.value = ''; });
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-other-description').isVisible(), 'Other validation must reopen the picker');
  await page.locator('#request-other-description').fill('A bespoke service to discuss');
  await page.locator('#request-extra-details>summary').click();

  const picker = page.locator('#request-proposals');
  await picker.setInputFiles([pdf, docx]);
  assert.equal(await page.locator('#request-file-list li').count(), 2);
  await picker.setInputFiles({ name: 'unsafe.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('not a proposal') });
  assert(await page.locator('#request-upload-error').isVisible());
  assert.equal(await page.locator('#request-file-list li').count(), 2);
  await picker.setInputFiles({ ...pdf, name: 'wrong-content-type.pdf', mimeType: 'application/javascript' });
  assert(await page.locator('#request-upload-error').isVisible());
  assert.equal(await page.locator('#request-file-list li').count(), 2);
  await picker.setInputFiles({ ...pdf, name: 'too-large.pdf', buffer: Buffer.alloc(10 * 1024 * 1024 + 1) });
  assert.match(await page.locator('#request-upload-error').textContent(), /10 MB/);
  await picker.setInputFiles({ ...pdf, name: 'empty.pdf', buffer: Buffer.alloc(0) });
  assert.match(await page.locator('#request-upload-error').textContent(), /Empty/);
  await page.locator('#request-file-list button').first().click();
  assert.equal(await page.locator('#request-file-list li').count(), 1);
  await picker.setInputFiles(pdf);
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-review').isVisible());
  assert.equal(await page.locator('#request-summary img').count(), 0, 'Summary must render client content as text');
  assert.match(await page.locator('#request-summary').textContent(), /<img src=x onerror=alert\(1\)>/);
  if (!process.env.SERVICE_REQUEST_CONNECTED_BUILD) {
    assert(await page.locator('#request-send').isDisabled());
    assert.match(await page.locator('#request-review-note').textContent(), /nothing has been sent/i);
    assert.equal(posts.length, 0);
  }
  const downloaded = page.waitForEvent('download');
  await page.locator('#request-download').click();
  assert.equal((await downloaded).suggestedFilename(), 'brandship-project-brief.txt');
  await page.locator('#request-edit').click();
  assert.equal(await page.locator('#request-other-description').inputValue(), 'A bespoke service to discuss');
  assert.equal(await page.locator('#request-file-list li').count(), 2);
  await page.evaluate(() => { document.querySelector('.service-request-form').dataset.endpoint = 'https://forms.brandship.test/service-requests'; });
  await page.locator('#request-review-button').click();
  assert(await page.locator('#request-send').isEnabled());
  await page.locator('#request-send').click();
  await page.locator('#request-send').dispatchEvent('click');
  await page.waitForFunction(() => document.querySelector('#enquiry-status').textContent.includes('could not confirm'));
  assert.equal(posts.length, 1, 'Double clicks must not duplicate a submission');
  assert(await page.locator('#request-success').isHidden());
  assert.equal(await page.locator('#request-file-list li').count(), 2);
  for (const item of ['name="proposals"', 'ready-proposal.pdf', 'reference.docx', 'visual-identity', 'other_service', 'client_request_id', 'name="form_version"\r\n\r\n2']) assert(posts[0].includes(item), `Missing multipart field: ${item}`);
  assert(!/name="(?:budget|timeline)"/.test(posts[0]), 'Removed questions must not be sent');
  outcome = 'unconfirmed';
  await page.locator('#request-send').click();
  await page.waitForFunction(() => document.querySelector('#request-send').disabled === false);
  assert(await page.locator('#request-success').isHidden(), 'HTTP 200 without ok:true must not show success');
  outcome = 'success';
  await page.locator('#request-send').click();
  await page.locator('#request-success').waitFor();
  assert.equal(posts.length, 3);
  const ids = posts.map(post => post.match(/name="client_request_id"\r\n\r\n([^\r]+)/)?.[1]);
  assert(ids[0] && ids.every(id => id === ids[0]), 'Retries must reuse the idempotency ID');
  await page.locator('#request-start-again').click();
  assert.equal(await page.locator('#request-name').inputValue(), '');
  assert.equal(await page.locator('#request-file-list li').count(), 0);
  await picker.setInputFiles(Array.from({ length: 4 }, (_, i) => ({ ...pdf, name: `proposal-${i}.pdf` })));
  assert.match(await page.locator('#request-upload-error').textContent(), /3 files/);
  await picker.setInputFiles(Array.from({ length: 3 }, (_, i) => ({ ...pdf, name: `large-${i}.pdf`, buffer: Buffer.alloc(8 * 1024 * 1024) })));
  assert.match(await page.locator('#request-upload-error').textContent(), /20 MB/);
  assert.equal(await page.locator('#request-file-list li').count(), 0);
  await page.evaluate(() => {
    const transfer = new DataTransfer();
    transfer.items.add(new File(['%PDF-Test'], 'dropped-proposal.pdf', { type: 'application/pdf' }));
    document.querySelector('#request-dropzone').dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }));
  });
  assert.equal(await page.locator('#request-file-list li').count(), 1);
  await page.locator('#request-service-picker>summary').click();
  await page.locator('#request-other').check();
  await page.locator('#request-other-description').fill('A custom request');
  await page.locator('#request-other').uncheck();
  assert(await page.locator('#request-other-description').isDisabled());
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    for (const expanded of [false, true]) {
      await page.locator('#request-service-picker').evaluate((e, open) => { e.open = open; }, expanded);
      await page.locator('#request-extra-details').evaluate((e, open) => { e.open = open; }, expanded);
      for (const fraction of [0, .5, 1]) {
        await page.evaluate(f => scrollTo({ top: (document.documentElement.scrollHeight - innerHeight) * f, behavior: 'instant' }), fraction);
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Form overflow at ${width}px`);
      }
    }
    if (width <= 800) assert(parseFloat(await page.locator('#request-name').evaluate(e => getComputedStyle(e).fontSize)) >= 16, 'Mobile inputs must avoid automatic zoom');
  }
  await page.goto(new URL(`${route}?service=strategy&service=unknown&endpoint=https://untrusted.example/upload`, base).href);
  await page.locator('[data-request-ready="true"]').waitFor();
  assert(await page.locator('[name=services][value=strategy]').isChecked());
  assert.equal(await page.locator('[name=services]:checked').count(), 1, 'Only known service keys can be preselected');
  if (!process.env.SERVICE_REQUEST_CONNECTED_BUILD) assert(await page.locator('#request-send').isDisabled(), 'Query parameters must not enable an upload destination');
  assert.deepEqual(errors, []);
  console.log('Short enquiry, note-or-proposal validation, optional details, service catalogue, files/limits/drop/removal, safe review, mocked delivery/retries and 4 responsive widths: passed');
} finally { await browser.close(); }
