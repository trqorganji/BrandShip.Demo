import assert from 'node:assert/strict';
import { stat } from 'node:fs/promises';
import { partners, people, directors } from '../src/team-people-data.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.RESPONSIVE_BASE_URL || 'http://localhost:5173/';
assert.equal(partners.length, 5);
assert.equal(people.length, 31);
assert.equal(directors.length, 5);
assert.equal(new Set([...partners, ...people].map(person => person.id)).size, 36);
let bytes = 0;
for (const person of [...partners, ...people]) {
  const file = await stat(new URL(`../public/${person.image}`, import.meta.url));
  assert(file.size > 0 && file.size < 400000, `${person.name}: portrait size`);
  bytes += file.size;
  assert.equal(person.quote, null, 'No director quotes have been approved yet');
}
