  await page.waitForTimeout(3500);
  await expectPerson(people[5].id);
  await page.locator('#people-previous').click();
  await expectPerson(people[4].id);
  await page.waitForFunction(() => document.querySelector('#people-profile').getAnimations().some(animation => animation.effect.getKeyframes().some(frame => frame.transform === 'translateX(-48px)')));
  assert.equal(await page.locator('.people-carousel').getAttribute('data-direction'), 'previous', 'Previous reverses the transition');
  await page.waitForFunction(() => document.querySelector('.people-carousel').dataset.transitioning === 'false');
  assert.equal(await page.locator('.people-carousel').getAttribute('data-playing'), 'true', 'A pointer click resumes autoplay after keyboard use');
  await page.locator('#people-next').evaluate(button => { button.click(); button.click(); button.click(); });
  await expectPerson(people[7].id);
  await page.waitForFunction(() => document.querySelector('.people-carousel').dataset.transitioning === 'false');
  assert.equal(await page.locator('#people-profile').getAttribute('aria-busy'), 'false', 'Rapid clicks must settle on the latest requested person');
  assert.equal(await page.locator('#people-profile').evaluate(element => element.getAnimations().length), 0, 'No accumulated animations or duplicate profiles');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.locator('#people-previous').click();
  await expectPerson(people[6].id);
