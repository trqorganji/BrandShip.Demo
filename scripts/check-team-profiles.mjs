  await page.waitForFunction(() => document.querySelector('#people-profile').getAnimations().some(animation => animation.effect.getKeyframes().some(frame => frame.transform === 'translateX(48px)')));
  assert.equal(await page.locator('.people-carousel').getAttribute('data-direction'), 'next', 'Autoplay enters from the right');
  await page.waitForFunction(() => document.querySelector('.people-carousel').dataset.transitioning === 'false');
  await page.locator('.people-portrait').hover();
  assert.equal(await page.locator('.people-carousel').getAttribute('data-playing'), 'true', 'Hovering over a portrait must not stop autoplay');
  await page.locator(`.people-carousel[data-person="${people[2].id}"]`).waitFor({ timeout: 4500 });
  await page.locator('#people-next').click();
  await expectPerson(people[3].id);
  await page.waitForFunction(() => document.querySelector('.people-carousel').dataset.transitioning === 'false');
  assert.equal(await page.locator('#people-next').evaluate(button => document.activeElement === button), true);
  await page.waitForFunction(() => document.querySelector('.people-carousel').dataset.playing === 'true');
  await page.locator(`.people-carousel[data-person="${people[4].id}"]`).waitFor({ timeout: 4500 });
