  assert.deepEqual(errors, []);
  console.log('36 portraits, fixed board, 31 employees, no counter, directional transitions, rapid clicks, mobile swipe, autoplay while hovered/after clicks, keyboard pause/pointer resume, reduced motion and director placeholders: passed');
